const SENTIMENT_LABELS = {
  positive: 'Positive',
  neutral:  'Neutral',
  mixed:    'Mixed',
  tense:    'Tense',
};

// Actions below read the saved notes, so they pause while there are unsaved edits.
const EDITING_HINT = 'Save or discard your edits first';

function editedLabel(iso) {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? 'Edited' : `Edited ${d.toLocaleString()}`;
}

function metaChips(session, notes, providers) {
  const sentiment = SENTIMENT_LABELS[notes?.sentiment];
  const hostname = meetingHostname(session.meeting_url);
  const platform = meetingPlatform(session.meeting_url);
  const stt = notes?._sttService && notes._sttService !== 'none' ? providerName(providers, 'stt', notes._sttService) : null;
  const llmModel = notes?._llmModel || notes?._geminiModel;

  const chips = [];
  if (sentiment) chips.push(<span key="sentiment" className="pill-quiet">{sentiment}</span>);
  if (notes) {
    chips.push(
      <span key="mode" className="pill-quiet">{notes._rawMarkdown ? 'Markdown' : 'JSON'}</span>
    );
    if (notes._editedAt) {
      chips.push(
        <span key="edited" className="pill-quiet" title={editedLabel(notes._editedAt)}>Edited</span>
      );
    }
  }
  if (llmModel) {
    const llm = notes?._llmProvider ? providerName(providers, 'llm', notes._llmProvider) : '';
    chips.push(
      <span key="model" className="pill-quiet" title={`Notes generated by ${llm ? `${llm} · ` : ''}${llmModel}`}>
        {llmModel}
      </span>
    );
  }
  if (stt) {
    chips.push(
      <span key="stt" className="pill-quiet" title={`Transcribed with ${stt}${notes?._sttModel ? ` · ${notes._sttModel}` : ''}`}>{stt}</span>
    );
  }
  if (hostname) {
    chips.push(
      <button
        key="host"
        type="button"
        className="pill-quiet hover:text-ink hover:border-ink transition-colors"
        onClick={() => window.meetmind?.shell?.openExternal(session.meeting_url)}
        title={`Open ${session.meeting_url}`}
      >
        {platform?.icon && (
          <img src={platform.icon} alt="" className="w-16 h-16 object-contain logo-mono" aria-hidden="true" />
        )}
        {hostname}
      </button>
    );
  }
  return chips;
}

// A single "Notion" button for a meeting that already has a page; it opens a small menu with
// the two things you can do with that page: open it, or replace it with the current notes.
function NotionMenu({ notionUrl, uploading, updateDisabled, updateTitle, onUpdate }) {
  return (
    <Menu
      label="Notion page"
      trigger={({ open, ...props }) => (
        <button
          type="button"
          {...props}
          disabled={uploading}
          title={uploading ? 'Updating the Notion page…' : 'Notion page'}
          className="btn-ghost px-16 py-4 text-caption"
        >
          {uploading ? <Loader2 size={14} strokeWidth={2} className="spinner" /> : <NotionIcon size={14} />}
          {uploading ? 'Updating…' : 'Notion'}
          <ChevronDown
            size={14}
            strokeWidth={1.75}
            aria-hidden="true"
            className={`transition-transform duration-150 ${open ? 'rotate-180' : ''}`}
          />
        </button>
      )}
    >
      <MenuItem
        icon={<ExternalLink size={14} strokeWidth={1.75} aria-hidden="true" />}
        onSelect={() => window.meetmind.shell.openExternal(notionUrl)}
      >
        Open in Notion
      </MenuItem>
      <MenuItem
        icon={<CloudUpload size={14} strokeWidth={1.75} aria-hidden="true" />}
        onSelect={onUpdate}
        disabled={updateDisabled}
        title={updateTitle}
      >
        Update page
      </MenuItem>
    </Menu>
  );
}

// Slim sticky bar: back, view tabs and note actions on one row. The meeting
// title only appears here once the in-page title has scrolled out of view.
// A 1fr/auto/1fr grid keeps the tabs centred on the bar whatever the widths of
// the side columns (title visibility, Notion state, notes missing); the actions
// column never shrinks below its content, so at narrow widths the tabs shift left
// instead of being overlapped.
export function NoteToolbar({
  title,
  showTitle,
  notes,
  tabs,
  activeTab,
  onTabChange,
  onBack,
  busy,
  copied,
  onCopy,
  regenerating,
  regenerate,
  exporting,
  onExportPdf,
  notionUrl,
  uploading,
  onSyncNotion,
  editing,
  onDelete,
  deleting,
}) {
  const lockTitle = editing ? { title: EDITING_HINT } : {};
  return (
    <header className="relative z-20 flex-shrink-0 border-b border-ink bg-paper">
      <div className="w-full px-24 py-8 grid grid-cols-[minmax(0,1fr)_auto_minmax(max-content,1fr)] items-center gap-16">
        <div className="flex items-center gap-16 min-w-0">
          <IconButton label="Back to meetings" onClick={onBack} className="flex-shrink-0">
            <ChevronLeft size={18} strokeWidth={1.75} />
          </IconButton>

          <p
            aria-hidden="true"
            title={title}
            className={`flex-1 min-w-0 truncate text-body-sm font-medium text-ink transition-opacity duration-150 ${
              showTitle ? 'opacity-100' : 'opacity-0'
            }`}
          >
            {title}
          </p>
        </div>

        <SegmentedControl
          label="Meeting views"
          options={tabs}
          value={activeTab}
          onChange={onTabChange}
          size="sm"
        />

        <div className="flex items-center justify-end gap-4 min-w-0">
          {notes && (
            <>
              <IconButton
                label={copied ? 'Copied' : 'Copy notes as Markdown'}
                onClick={onCopy}
                disabled={editing}
                {...lockTitle}
              >
                {copied ? <Check size={16} strokeWidth={2} /> : <Copy size={16} strokeWidth={1.75} />}
              </IconButton>

              <IconButton
                label={exporting ? 'Exporting PDF…' : 'Export as PDF'}
                onClick={onExportPdf}
                disabled={editing || exporting}
                {...lockTitle}
              >
                {exporting
                  ? <Loader2 size={16} strokeWidth={2} className="spinner" />
                  : <FileDown size={16} strokeWidth={1.75} />}
              </IconButton>

              {/* Labelled, with an icon per action, because what it regenerates follows the tab.
                  Below lg the label hides and the icon alone tells the two apart. */}
              <button
                type="button"
                onClick={regenerate.onClick}
                disabled={editing || busy || regenerating || uploading || !!regenerate.unavailable}
                aria-label={regenerating ? 'Regenerating…' : regenerate.title || regenerate.label}
                title={editing ? EDITING_HINT : regenerate.unavailable || regenerate.title || regenerate.label}
                className="btn-ghost px-8 py-4 text-caption lg:px-16 mr-4"
              >
                {regenerating ? (
                  <Loader2 size={14} strokeWidth={2} className="spinner" />
                ) : (
                  <regenerate.icon key={`icon-${regenerate.title || regenerate.label}`} size={14} strokeWidth={1.75} className="fade-in" aria-hidden="true" />
                )}
                <span key={`label-${regenerate.label}`} className="hidden lg:inline fade-in">
                  {regenerating ? 'Regenerating…' : regenerate.label}
                </span>
              </button>

              {notionUrl ? (
                <NotionMenu
                  notionUrl={notionUrl}
                  uploading={uploading}
                  updateDisabled={editing || uploading || busy}
                  updateTitle={editing ? EDITING_HINT : 'Replace the Notion page with the current notes'}
                  onUpdate={onSyncNotion}
                />
              ) : (
                <button
                  type="button"
                  onClick={onSyncNotion}
                  disabled={editing || uploading || busy}
                  className="btn-ghost px-16 py-4 text-caption"
                  title={editing ? EDITING_HINT : 'Upload notes to Notion'}
                >
                  {uploading ? <Loader2 size={14} strokeWidth={2} className="spinner" /> : <NotionIcon size={14} />}
                  {uploading ? 'Syncing…' : 'Sync to Notion'}
                </button>
              )}
            </>
          )}

          {/* Always available, including for failed or still-processing meetings that have no notes. */}
          <IconButton
            label={deleting ? 'Deleting meeting…' : 'Delete meeting'}
            onClick={onDelete}
            disabled={deleting || uploading}
            className="hover:text-signal hover:border-signal"
          >
            {deleting
              ? <Loader2 size={16} strokeWidth={1.75} className="spinner" />
              : <Trash2 size={16} strokeWidth={1.75} />}
          </IconButton>
        </div>
      </div>
    </header>
  );
}

const TITLE_MAX_LENGTH = 200; // matches cleanTitle() in electron/services/meeting-title.js
const TITLE_COUNT_FROM = 40;  // characters left when the counter appears

// The meeting title, renamed in place: the pencil (or a double-click) turns it into a field
// set in the same type and width, so a title that wraps keeps its lines and the text doesn't
// move. Enter or leaving the field saves, Escape cancels. `onRename` resolves true once
// saved; on failure the field stays open.
function EditableTitle({ title, onRename, disabledReason }) {
  const [editing, setEditing] = useState(false);
  const [value, setValue] = useState(title);
  const [saving, setSaving] = useState(false);
  const inputRef = useRef(null);
  // Blur also fires after Enter or Escape; these keep it from saving twice or after a cancel.
  const busyRef = useRef(false);
  const cancelledRef = useRef(false);
  const canRename = !!onRename && !disabledReason;

  // Near the limit the field shows how much is left, so a long name isn't cut off unnoticed.
  const showCount = value.length >= TITLE_MAX_LENGTH - TITLE_COUNT_FROM;

  useEffect(() => {
    if (editing) inputRef.current?.select();
  }, [editing]);

  // The field grows to fit its wrapped lines instead of scrolling, and refits when the window
  // width changes. Collapsing it to measure would clamp the page's scroll position; keep it.
  useLayoutEffect(() => {
    const el = inputRef.current;
    if (!editing || !el) return undefined;
    const fit = () => {
      const scroller = el.closest('.overflow-y-auto');
      const top = scroller?.scrollTop;
      el.style.height = 'auto';
      el.style.height = `${el.scrollHeight + 2}px`; // + the 1px top and bottom borders
      if (scroller) scroller.scrollTop = top;
    };
    fit();
    let width = el.offsetWidth;
    const observer = new ResizeObserver(() => {
      if (el.offsetWidth === width) return; // our own height change
      width = el.offsetWidth;
      fit();
    });
    observer.observe(el);
    return () => observer.disconnect();
  }, [editing, value, showCount, saving]);

  const start = () => {
    if (!canRename) return;
    cancelledRef.current = false;
    setValue(title);
    setEditing(true);
  };

  const cancel = () => {
    cancelledRef.current = true;
    setEditing(false);
  };

  const commit = async () => {
    if (busyRef.current || cancelledRef.current) return;
    const next = value.replace(/\s+/g, ' ').trim();
    if (!next || next === title) {
      setEditing(false);
      return;
    }
    busyRef.current = true;
    setSaving(true);
    const ok = await onRename(next);
    busyRef.current = false;
    setSaving(false);
    if (ok) setEditing(false);
    else inputRef.current?.focus();
  };

  if (editing) {
    // The field reaches 17px (padding + border) past the title on both sides, so its text
    // box is exactly the title's width and wraps at the same words. The counter and the
    // saving spinner sit in an extra strip at the bottom, so they never narrow the text.
    const footer = saving || showCount;
    return (
      <div className="relative min-w-0 flex-1">
        <textarea
          ref={inputRef}
          value={value}
          rows={1}
          // A title is one line: pasted line breaks become spaces.
          onChange={(e) => setValue(e.target.value.replace(/[\r\n]+/g, ' '))}
          onBlur={commit}
          onKeyDown={(e) => {
            if (e.key === 'Enter') {
              e.preventDefault();
              commit();
            } else if (e.key === 'Escape') {
              e.preventDefault();
              e.stopPropagation();
              cancel();
            }
          }}
          readOnly={saving}
          maxLength={TITLE_MAX_LENGTH}
          aria-label="Meeting title"
          spellCheck
          aria-describedby={showCount ? 'meeting-title-count' : undefined}
          className={`input block w-[calc(100%+34px)] -mx-[17px] -my-[9px] py-8 text-heading font-medium resize-none overflow-hidden ${
            footer ? 'pb-32' : ''
          }`}
        />
        {footer && (
          <span className="absolute right-0 bottom-0 flex items-center text-caption text-graphite tabular-nums pointer-events-none">
            {saving ? (
              <Loader2 size={16} strokeWidth={2} className="spinner" aria-label="Saving title" />
            ) : (
              <span id="meeting-title-count">{value.length}/{TITLE_MAX_LENGTH}</span>
            )}
          </span>
        )}
      </div>
    );
  }

  // The pencil sits inline after the last word, so it stays next to a title that wraps.
  return (
    <div className="group min-w-0 flex-1 break-words">
      <h1 className="inline text-heading font-medium text-ink" onDoubleClick={start}>
        {title}
      </h1>
      {onRename && (
        <IconButton
          label={disabledReason || 'Rename meeting'}
          onClick={start}
          disabled={!canRename}
          className="ml-8 align-[2px] opacity-0 group-hover:opacity-100 focus-visible:opacity-100 transition-opacity"
        >
          <Pencil size={16} strokeWidth={1.75} />
        </IconButton>
      )}
    </div>
  );
}

// Title, meta line and chips at the top of the scrolling body, so they scroll
// away with the notes instead of permanently taking up the viewport. The ref is
// on the title row (not the heading) because renaming swaps the heading for a field.
export const NoteTitleBlock = forwardRef(function NoteTitleBlock(
  { session, notes, title, durationLabel, processingError, aside, onRename, renameDisabledReason },
  ref,
) {
  const meta = metaText(session, notes, durationLabel);
  const { providers } = useApp();
  const chips = metaChips(session, notes, providers);

  return (
    <div className="pt-32 pb-8">
      <div ref={ref} className="flex items-start justify-between gap-32">
        <EditableTitle title={title} onRename={onRename} disabledReason={renameDisabledReason} />
        {aside && <div className="flex-shrink-0 mt-4">{aside}</div>}
      </div>
      {(meta || chips.length > 0) && (
        <div className="flex items-center flex-wrap gap-8 mt-8">
          {meta && <p className="text-body-sm text-graphite mr-8">{meta}</p>}
          {chips}
        </div>
      )}
      {processingError && (
        <p role="alert" className="flex items-start gap-8 text-caption text-signal mt-16">
          <AlertTriangle size={16} strokeWidth={1.75} className="flex-shrink-0 mt-[2px]" />
          <span className="min-w-0 break-words">{processingError}</span>
        </p>
      )}
    </div>
  );
});
